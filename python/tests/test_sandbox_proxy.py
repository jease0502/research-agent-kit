"""templates/sandbox/egress_proxy.py end to end on localhost: a real proxy, a stand-in upstream, real TLS ClientHellos
(generated by Python's ssl module, not hand-written). Review of 6555c3c, H1/L1/L2: a tunnel to an allowed host must
not carry a TLS session for another name (domain fronting: DNS over HTTPS through api.anthropic.com's CDN), the
proxy connects to the address it checked, and never to a private one.

RAK_PROXY_UNDER_TEST=<path> runs the same tests against another copy (used to show them red on the old proxy)."""
from __future__ import annotations

import asyncio
import importlib.util
import os
import socket
import ssl
from pathlib import Path

import pytest

SANDBOX = Path(__file__).resolve().parents[2] / "templates" / "sandbox"


def _load():
    path = Path(os.environ.get("RAK_PROXY_UNDER_TEST") or SANDBOX / "egress_proxy.py")
    spec = importlib.util.spec_from_file_location("egress_proxy_under_test", path)
    m = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(m)
    return m


P = _load()
ALLOW = P.load_allow("api.anthropic.com arxiv.org")


def client_hello(sni: str | None, ech: bool = False) -> bytes:
    ctx = ssl.create_default_context()
    ctx.check_hostname = sni is not None
    if sni is None:
        ctx.verify_mode = ssl.CERT_NONE
    inc, out = ssl.MemoryBIO(), ssl.MemoryBIO()
    obj = ctx.wrap_bio(inc, out, server_hostname=sni)
    try:
        obj.do_handshake()
    except ssl.SSLWantReadError:
        pass
    data = out.read()
    if ech:          # append an encrypted_client_hello extension (0xfe0d) the way a client would, lengths fixed up
        data = _add_extension(data, 0xFE0D, b"\x00" * 8)
    return data


def _add_extension(rec: bytes, etype: int, body: bytes) -> bytes:
    hs = bytearray(rec[5:])
    h = hs[4:]
    p = 2 + 32
    p += 1 + h[p]
    p += 2 + int.from_bytes(h[p:p + 2], "big")
    p += 1 + h[p]
    ext_len = int.from_bytes(h[p:p + 2], "big")
    ext = etype.to_bytes(2, "big") + len(body).to_bytes(2, "big") + body
    h[p:p + 2] = (ext_len + len(ext)).to_bytes(2, "big")
    h += ext
    hs = bytearray([hs[0]]) + len(h).to_bytes(3, "big") + h
    return rec[:3] + len(hs).to_bytes(2, "big") + bytes(hs)


def run_tunnel(monkeypatch, connect_host: str, hello: bytes, resolved: str = "93.184.216.34"):
    """Proxy on localhost; DNS and the upstream connection are stand-ins. Returns (proxy reply, bytes upstream got,
    address the proxy dialled)."""
    got, dialled = bytearray(), []

    async def scenario():
        async def upstream(r, w):
            got.extend(await r.read(65536))
            w.close()

        up = await asyncio.start_server(upstream, "127.0.0.1", 0)
        up_port = up.sockets[0].getsockname()[1]
        loop = asyncio.get_running_loop()

        async def fake_getaddrinfo(host, port, **kw):
            return [(socket.AF_INET, socket.SOCK_STREAM, 6, "", (resolved, port))]

        real_open = asyncio.open_connection

        async def fake_open(host, port, **kw):
            dialled.append(host)
            return await real_open("127.0.0.1", up_port)

        monkeypatch.setattr(loop, "getaddrinfo", fake_getaddrinfo)
        monkeypatch.setattr(P.asyncio, "open_connection", fake_open)
        handler = (lambda r, w: P.handle(r, w, ALLOW, asyncio.Semaphore(4))) if hasattr(P, "MAX_CONNECTIONS") \
            else (lambda r, w: P.handle(r, w, ALLOW))
        srv = await asyncio.start_server(handler, "127.0.0.1", 0)
        port = srv.sockets[0].getsockname()[1]
        r, w = await real_open("127.0.0.1", port)
        w.write(f"CONNECT {connect_host}:443 HTTP/1.1\r\nHost: {connect_host}:443\r\n\r\n".encode())
        await w.drain()
        reply = await asyncio.wait_for(r.readuntil(b"\r\n\r\n"), 5)
        if reply.startswith(b"HTTP/1.1 200"):
            w.write(hello)
            await w.drain()
            try:
                await asyncio.wait_for(r.read(1), 2)
            except (asyncio.TimeoutError, ConnectionError):
                pass
        w.close()
        await asyncio.sleep(0.2)
        srv.close()
        up.close()
        return reply

    reply = asyncio.run(scenario())
    return reply, bytes(got), dialled


def test_matching_sni_is_forwarded(monkeypatch):
    hello = client_hello("api.anthropic.com")
    reply, got, dialled = run_tunnel(monkeypatch, "api.anthropic.com", hello)
    assert reply.startswith(b"HTTP/1.1 200")
    assert got == hello, "the ClientHello must reach the upstream unchanged"
    assert dialled == ["93.184.216.34"], "connect to the checked address, not the name again"


@pytest.mark.parametrize("sni", ["cloudflare-dns.com", "one.one.one.one", "api.anthropic.com.evil.net"])
def test_domain_fronting_is_cut(monkeypatch, sni):
    """A bypass found in review: CONNECT to an allowed host, then TLS for another name on the same CDN."""
    _, got, _ = run_tunnel(monkeypatch, "api.anthropic.com", client_hello(sni))
    assert got == b"", f"a ClientHello for {sni} went upstream through a tunnel to api.anthropic.com"


def test_no_sni_is_cut(monkeypatch):
    _, got, _ = run_tunnel(monkeypatch, "api.anthropic.com", client_hello(None))
    assert got == b""


def test_encrypted_client_hello_is_cut(monkeypatch):
    _, got, _ = run_tunnel(monkeypatch, "api.anthropic.com", client_hello("api.anthropic.com", ech=True))
    assert got == b""


def test_not_tls_is_cut(monkeypatch):
    _, got, _ = run_tunnel(monkeypatch, "api.anthropic.com", b"GET /dns-query HTTP/1.1\r\nHost: x\r\n\r\n")
    assert got == b""


@pytest.mark.parametrize("addr", ["127.0.0.1", "10.0.0.5", "192.168.65.2", "169.254.169.254", "172.17.0.1", "::1",
                                  "fd00::1"])
def test_private_addresses_are_refused(monkeypatch, addr):
    reply, got, dialled = run_tunnel(monkeypatch, "api.anthropic.com", client_hello("api.anthropic.com"), addr)
    assert reply.startswith(b"HTTP/1.1 403") and got == b"" and dialled == []


def test_trailing_dots_connect_by_the_normalized_name(monkeypatch):
    reply, got, _ = run_tunnel(monkeypatch, "arxiv.org.", client_hello("arxiv.org"))
    assert reply.startswith(b"HTTP/1.1 200") and got


def test_repeated_sni_extension_is_cut(monkeypatch):
    """Review of 1a90306 (low): with two server_name extensions the parser took the last; now it takes neither."""
    # the attacker's order: the real target first, the allowed name last (the old parser kept the last one)
    good = client_hello("cloudflare-dns.com")
    second = client_hello("api.anthropic.com")
    sni_body = P.client_hello_sni(second)[0].encode()
    entry = b"\x00" + len(sni_body).to_bytes(2, "big") + sni_body
    ext_body = len(entry).to_bytes(2, "big") + entry
    doubled = _add_extension(good, 0x0000, ext_body)
    assert P.client_hello_sni(doubled)[0] is None
    _, got, _ = run_tunnel(monkeypatch, "api.anthropic.com", doubled)
    assert got == b""
